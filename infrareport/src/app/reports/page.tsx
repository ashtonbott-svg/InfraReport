"use client";

import Link from "next/link";
import { useMemo } from "react";
import { Download, FileSpreadsheet, FileText, Lock } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Card, CardBody, CardHeader } from "@/components/ui/card";
import { Badge, StatusBadge } from "@/components/ui/badge";
import { PageHeader, Table, td, th } from "@/components/ui/misc";
import { toast } from "@/components/ui/toast";
import { useAllowedCauses, useCustomers, useEquipment, useFacilities, useInspections, useLocations, useOrganization, useResults, useRooms } from "@/lib/store/hooks";
import { useStore } from "@/lib/store/store";
import { buildGeneratorRows, exportFileName, toCsv, type ExportDataset } from "@/lib/domain/csv";
import { countBySeverity, validateInspection } from "@/lib/domain/validation";
import { POSSIBLE_CAUSE_NONE } from "@/lib/domain/constants";
import { downloadText } from "@/lib/download";
import { formatDate } from "@/lib/format";

export default function ReportsPage() {
  const inspections = useInspections();
  const customers = useCustomers();
  const facilities = useFacilities();
  const results = useResults();
  const equipment = useEquipment();
  const locations = useLocations();
  const rooms = useRooms();
  const causes = useAllowedCauses();
  const org = useOrganization();
  const logEvent = useStore((s) => s.logEvent);

  const rows = useMemo(() => {
    const eqMap = new Map(equipment.map((e) => [e.id, e]));
    const locMap = new Map(locations.map((l) => [l.id, l]));
    return [...inspections].sort((a, b) => b.date.localeCompare(a.date)).map((inspection) => {
      const ds: ExportDataset = { inspection, results: results.filter((r) => r.inspectionId === inspection.id), equipment: eqMap, locations: locMap, rooms: rooms.filter((r) => r.inspectionId === inspection.id) };
      const counts = countBySeverity(validateInspection(ds, { allowedCauses: causes }));
      return {
        inspection, ds, counts,
        customer: customers.find((c) => c.id === inspection.customerId)?.name ?? "",
        facility: facilities.find((f) => f.id === inspection.facilityId)?.name ?? "",
        problems: ds.results.filter((r) => r.possibleCause !== POSSIBLE_CAUSE_NONE).length,
      };
    });
  }, [inspections, results, equipment, locations, rooms, causes, customers, facilities]);

  const exportOne = (r: (typeof rows)[number]) => {
    const data = buildGeneratorRows(r.ds);
    downloadText(exportFileName(r.customer, r.facility, r.inspection.date), toCsv(data, { includeBom: org?.settings.csvIncludeBom ?? true }));
    logEvent(r.inspection.id, "Generator CSV exported", `${data.length} rows, 16 columns`);
    toast(`Exported ${data.length} rows`);
  };

  return (
    <>
      <PageHeader title="Reports" description="Report readiness, validation status, and exports for every inspection." />
      <div className="mb-6 grid gap-3 md:grid-cols-3">
        <Card><CardBody className="flex gap-3"><FileSpreadsheet className="h-5 w-5 shrink-0 text-emerald-600" /><div><div className="text-sm font-semibold">Generator CSV</div><div className="text-xs text-slate-500">Available now. Exact 16 column layout for your Excel Generator.</div></div></CardBody></Card>
        <Card><CardBody className="flex gap-3"><Lock className="h-5 w-5 shrink-0 text-slate-400" /><div><div className="text-sm font-semibold">Excel workbook population</div><div className="text-xs text-slate-500">Planned after reviewing your actual workbook. Columns O, P, Q stay untouched.</div></div></CardBody></Card>
        <Card><CardBody className="flex gap-3"><FileText className="h-5 w-5 shrink-0 text-slate-400" /><div><div className="text-sm font-semibold">Finished PDF report</div><div className="text-xs text-slate-500">Not generated by InfraReport yet. Your existing Generator remains the report source.</div></div></CardBody></Card>
      </div>
      <Card>
        <CardHeader title="Inspections" />
        <Table>
          <thead><tr><th className={th}>Inspection</th><th className={th}>Status</th><th className={th}>Equipment</th><th className={th}>Problems</th><th className={th}>Validation</th><th className={th}>Exports</th></tr></thead>
          <tbody>
            {rows.map((r) => (
              <tr key={r.inspection.id} className="hover:bg-slate-50">
                <td className={td}>
                  <Link href={`/inspections/${r.inspection.id}/review`} className="font-medium text-slate-900 hover:text-thermal-700">{r.facility}</Link>
                  <div className="text-xs text-slate-500">{r.customer} · {formatDate(r.inspection.date)}</div>
                </td>
                <td className={td}><StatusBadge status={r.inspection.status} /></td>
                <td className={`${td} tabular-nums`}>{r.ds.results.length}</td>
                <td className={`${td} tabular-nums`}>{r.problems}</td>
                <td className={td}>
                  <div className="flex flex-wrap gap-1">
                    {r.counts.error ? <Badge tone="red">{r.counts.error} errors</Badge> : <Badge tone="green">No errors</Badge>}
                    {r.counts.warning ? <Badge tone="amber">{r.counts.warning} warnings</Badge> : null}
                  </div>
                </td>
                <td className={td}>
                  <div className="flex flex-wrap gap-2">
                    <Button size="sm" onClick={() => exportOne(r)} disabled={r.ds.results.length === 0}><Download className="h-3.5 w-3.5" />CSV</Button>
                    <Button size="sm" disabled title="Planned: requires Generator integration">Excel</Button>
                    <Button size="sm" disabled title="Planned: requires Generator integration">PDF</Button>
                  </div>
                </td>
              </tr>
            ))}
          </tbody>
        </Table>
      </Card>
    </>
  );
}
